"""Bundle shared camera + map controller + HA care UI into one HA local resource."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def build():
    parts = ('water-status.js', 'plant-clusters.js', 'plant-camera.js', 'ha-plant-map.js', 'ha-plants-card-source.js')
    output = '// Generated by build_ha_card.py; edit the source modules.\n'
    output += '\n;\n'.join((ROOT / p).read_text(encoding='utf-8') for p in parts)
    (ROOT / 'ha-plants-card.js').write_text(output, encoding='utf-8')


if __name__ == '__main__':
    build()
