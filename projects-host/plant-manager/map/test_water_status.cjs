const assert=require('node:assert/strict'),W=require('./water-status.js');
const now=Date.parse('2026-10-11T12:00:00Z'),day=86400000,at=d=>new Date(now-d*day).toISOString();
const b=(age,level=100)=>({id:'b1',capacity_ml:750,cycles:[],inspections:[{at:at(age),level}]});
const status=(bottles,forecasts=[],quarantine=false)=>W.plant({tracking:{1:{bottles,quarantine}},forecasts:{1:{bottles:forecasts}}},{id:1},now);
assert.equal(status([]).state,'red');
assert.equal(status([b(0)]).state,'green');
assert.equal(status([b(2)]).state,'yellow');
assert.equal(status([b(4)]).state,'red');
assert.equal(status([b(0,25)]).state,'yellow');
assert.equal(status([b(0,0)]).state,'red');
assert.equal(status([b(0)],[],true).state,'red');
assert.equal(status([b(0),{...b(0,0),id:'b2'}]).state,'red');
const f={id:'b1',ml_per_day:150,estimated_empty_at:at(-1)};
assert.equal(status([b(0)],[f]).state,'green');
assert.equal(status([b(4)],[f]).state,'yellow');
assert.equal(status([b(5)],[f]).state,'red');
assert.notEqual(status([b(0)]).colour,status([b(1)]).colour);
assert.equal(status([b(-1)]).state,'red');
const refill={id:'b1',capacity_ml:750,inspections:[{at:at(2),level:0}],cycles:[{filled_at:at(0),checks:[]}]};
assert.equal(status([refill]).state,'green');
refill.cycles[0].ended_at=at(0);assert.equal(status([refill]).state,'red');
console.log('Water rings: recent/low/empty/unknown, ageing, predictions, quarantine, multiple bottles, refills and future dates passed.');
